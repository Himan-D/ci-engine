export function searchNodeTypes(query: string): NodeTypeDef[] {
  if (!query) return ALL_NODE_TYPES
  const q = query.toLowerCase().replace(/^\//, '')
  return ALL_NODE_TYPES.filter(
    n =>
      n.label.toLowerCase().includes(q) ||
      n.type.includes(q) ||
      n.description.toLowerCase().includes(q) ||
      n.tags.some(t => t.includes(q)) ||
      n.category.toLowerCase().includes(q),
  )
}

export function getNodeType(type: string): NodeTypeDef {
  return ALL_NODE_TYPES.find(n => n.type === type) ?? ALL_NODE_TYPES[0]
}
